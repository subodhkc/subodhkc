/**
 * Build a canonical scope snapshot for a standard $500 Work Order.
 * The server generates this — the client does not supply the hash.
 */
export function buildStandardScopeSnapshot(params: {
  title: string
  workType: WorkType
  desiredOutcome: string
  scopeIncluded?: string
  scopeExcluded?: string
  requiredInputs?: string
  deliverableDescription?: string
  targetDate?: string | null
}): ScopeSnapshot {
  return {
    work_type: params.workType,
    title: params.title,
    desired_outcome: params.desiredOutcome,
    scope_included: params.scopeIncluded || 'One bounded piece of work as described in the intake and agreed in this scope.',
    scope_excluded: params.scopeExcluded || 'Work beyond the defined scope, additional integrations, or multi-system architecture. These may require additional Work Orders or a custom engagement.',
    required_inputs: params.requiredInputs || 'Access to relevant systems, data, or documentation as needed to complete the defined outcome.',
    deliverable_description: params.deliverableDescription || 'A focused deliverable matching the agreed scope: analysis, design, recommendation, configuration, or bounded implementation.',
    target_timing: params.targetDate || null,
    price_cents: 50000,
    currency: 'USD',
    assumptions: [
      'Standard Work Order covers one bounded outcome.',
      'If the work is larger than one standard Work Order, additional Work Orders or a custom scope will be discussed before proceeding.',
      'The answer is allowed to be no — a recommendation to wait, buy, or simplify is a valid outcome.',
    ],
  }
}

/**
 * Hash the scope snapshot for immutable acceptance record.
 */
export function hashScopeSnapshot(snapshot: ScopeSnapshot): string {
  const canonical = JSON.stringify({
    work_type: snapshot.work_type,
    title: snapshot.title,
    desired_outcome: snapshot.desired_outcome,
    scope_included: snapshot.scope_included,
    scope_excluded: snapshot.scope_excluded,
    required_inputs: snapshot.required_inputs,
    deliverable_description: snapshot.deliverable_description,
    target_timing: snapshot.target_timing,
    price_cents: snapshot.price_cents,
    currency: snapshot.currency,
    assumptions: snapshot.assumptions,
  })
  return createHash('sha256').update(canonical).digest('hex')
}

