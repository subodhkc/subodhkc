/**
 * Create a Work Order draft. work_order_number is auto-generated by trigger.
 */
export async function createWorkOrderDraft(opts: {
  organizationId: string
  requestedByUserId?: string
  title: string
  workType?: WorkType
  desiredOutcome?: string
  scopeIncluded?: string
  scopeExcluded?: string
  requiredInputs?: string
  deliverableDescription?: string
  legacyQualificationId?: string
  standardPriceCents?: number
  targetDate?: string | null
  metadata?: Record<string, unknown>
}): Promise<{ workOrderId: string; workOrderNumber: string } | { error: string }> {
  const sc = createServiceClient()
  if (!sc) return { error: 'Service client unavailable' }

  const { data, error } = await sc
    .from('ai_work_orders')
    .insert({
      organization_id: opts.organizationId,
      requested_by_user_id: opts.requestedByUserId || null,
      source_offer_key: 'ai_automation_blueprint',
      legacy_qualification_id: opts.legacyQualificationId || null,
      title: opts.title,
      work_type: opts.workType || 'other',
      desired_outcome: opts.desiredOutcome || null,
      scope_included: opts.scopeIncluded || null,
      scope_excluded: opts.scopeExcluded || null,
      required_inputs: opts.requiredInputs || null,
      deliverable_description: opts.deliverableDescription || null,
      scope_status: 'draft',
      status: 'draft',
      standard_price_cents: opts.standardPriceCents ?? 50000,
      currency: 'USD',
      target_date: opts.targetDate || null,
      metadata: opts.metadata || {},
    })
    .select('id, work_order_number')
    .single()

  if (error || !data) {
    return { error: error?.message || 'Failed to create Work Order' }
  }

  return { workOrderId: data.id, workOrderNumber: data.work_order_number }
}

